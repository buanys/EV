package ev.buan.gradle;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.TreeSet;
import java.util.stream.Stream;

/**
 * Renders the public API of one compiled Android library module as a stable text snapshot.
 *
 * <p>binary-compatibility-validator is the preferred tool, but this build has to work offline and
 * its Gradle plugin is not in the local dependency cache. The fallback is javap over the module's
 * compiled classes: a full JDK ships javap, no repository is touched, and the normalised output is
 * deterministic for a given compiler/JDK pair.
 *
 * <p>The snapshot is deliberately textual: CI compares the committed {@code api/<module>.txt} with
 * the freshly rendered text and fails on any difference, so an API change cannot land without the
 * baseline being updated in the same commit.
 */
public final class ApiSnapshot {

    private ApiSnapshot() {
    }

    /** Number of class names passed to one javap invocation; keeps the command line short. */
    private static final int JAVAP_BATCH = 80;

    public static String render(String moduleName, Collection<File> classRoots) {
        Set<String> classNames = new TreeSet<>();
        List<String> classpathEntries = new ArrayList<>();
        for (File root : classRoots) {
            if (root == null || !root.isDirectory()) {
                continue;
            }
            classpathEntries.add(root.getAbsolutePath());
            Path rootPath = root.toPath();
            try (Stream<Path> stream = Files.walk(rootPath)) {
                stream.filter(Files::isRegularFile)
                        .filter(path -> path.getFileName().toString().endsWith(".class"))
                        .forEach(path -> {
                            String relative = rootPath.relativize(path).toString();
                            String withDots = relative.replace(File.separatorChar, '.');
                            String className = withDots.substring(0, withDots.length() - ".class".length());
                            if (isCompilerGenerated(className)) {
                                return;
                            }
                            classNames.add(className);
                        });
            } catch (IOException error) {
                throw new IllegalStateException("Cannot scan API classes under " + root + ": " + error.getMessage(), error);
            }
        }
        if (classNames.isEmpty()) {
            throw new IllegalStateException(
                    "No compiled classes found for :" + moduleName + " under " + classRoots
                            + ". The module must be compiled before its API snapshot is rendered.");
        }

        String classpath = String.join(File.pathSeparator, classpathEntries);
        List<String> lines = new ArrayList<>();
        lines.add("# " + moduleName + " public API snapshot");
        lines.add("# Generated by :" + moduleName + ":apiSnapshot. Never edit by hand:");
        lines.add("# change the public API, run the task, and commit the resulting diff.");
        lines.add("");
        List<String> names = new ArrayList<>(classNames);
        for (int start = 0; start < names.size(); start += JAVAP_BATCH) {
            List<String> batch = names.subList(start, Math.min(start + JAVAP_BATCH, names.size()));
            lines.addAll(javap(classpath, batch));
        }
        return String.join("\n", lines) + "\n";
    }

    private static List<String> javap(String classpath, List<String> classNames) {
        File javap = javapExecutable();
        List<String> command = new ArrayList<>();
        command.add(javap.getAbsolutePath());
        command.add("-protected");
        command.add("-s");
        command.add("-classpath");
        command.add(classpath);
        command.addAll(classNames);

        ProcessBuilder builder = new ProcessBuilder(command);
        builder.redirectErrorStream(true);
        try {
            Process process = builder.start();
            String output = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
            int exit = process.waitFor();
            if (exit != 0) {
                throw new IllegalStateException(
                        "javap failed (exit " + exit + ") while rendering the API snapshot:\n" + output);
            }
            return normalize(output);
        } catch (IOException error) {
            throw new IllegalStateException("Cannot run javap: " + error.getMessage(), error);
        } catch (InterruptedException interrupted) {
            Thread.currentThread().interrupt();
            throw new IllegalStateException("Interrupted while running javap", interrupted);
        }
    }

    /**
     * Kotlin/Compose emit a few public-looking classes that are not part of the module's source
     * API: Compose's singleton holders, enum {@code $WhenMappings} tables and anonymous classes.
     * They change whenever the compiler feels like it, so they would make the snapshot noisy
     * without describing anything a plugin author can call.
     */
    private static boolean isCompilerGenerated(String className) {
        String simpleName = className.substring(className.lastIndexOf('.') + 1);
        return simpleName.startsWith("ComposableSingletons$")
                || simpleName.contains("$ComposableSingletons")
                || simpleName.endsWith("$WhenMappings")
                || simpleName.contains("$lambda")
                || simpleName.matches(".*\\$\\d+$");
    }

    /**
     * Keeps one canonical line per declaration: class headers as printed, members indented, and the
     * {@code descriptor:} line that follows a member kept next to it. Source names, blank lines and
     * javap warnings are dropped so the text only changes when the ABI does.
     *
     * <p>Synthetic Kotlin bridges ({@code access$...}, {@code foo$default(...)},
     * {@code copy$default(...)}) are dropped for the same reason as compiler-generated classes:
     * their names are an implementation detail, not an API a plugin can reasonably call.
     */
    private static List<String> normalize(String raw) {
        List<String> lines = new ArrayList<>();
        boolean dropFollowingDescriptor = false;
        for (String physical : raw.replace("\r\n", "\n").split("\n")) {
            String trimmed = physical.stripTrailing().trim();
            if (trimmed.isEmpty() || trimmed.equals("}")) {
                continue;
            }
            if (trimmed.startsWith("Compiled from ") || trimmed.startsWith("Warning: ")) {
                continue;
            }
            if (trimmed.startsWith("descriptor:")) {
                if (!dropFollowingDescriptor) {
                    lines.add("    " + trimmed);
                }
                dropFollowingDescriptor = false;
                continue;
            }
            if (trimmed.contains("access$") || trimmed.contains("$default(")) {
                dropFollowingDescriptor = true;
                continue;
            }
            dropFollowingDescriptor = false;
            if (trimmed.endsWith("{")) {
                lines.add(trimmed);
            } else {
                lines.add("  " + trimmed);
            }
        }
        return lines;
    }

    private static File javapExecutable() {
        String javaHome = System.getProperty("java.home");
        String executable = System.getProperty("os.name", "").toLowerCase(Locale.ROOT).contains("win")
                ? "javap.exe"
                : "javap";
        File candidate = new File(new File(javaHome, "bin"), executable);
        if (!candidate.isFile()) {
            throw new IllegalStateException(
                    "javap not found at " + candidate + ". A full JDK (not a JRE) is required for API snapshots.");
        }
        return candidate;
    }
}
